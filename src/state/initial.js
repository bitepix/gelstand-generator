// Начальные значения и форма дерева состояния. ТЗ v3, раздел 3.

/**
 * Значения полей ввода хранятся строками — ровно так, как их видит
 * пользователь, с запятой в роли разделителя. В число они превращаются
 * только в геометрии и валидации.
 */
export const initialFields = {
  width: '19,6',
  depth: '37',
  nx: '3',
  ny: '3',
}

export const initialState = {
  /** Шаг сценария: 1 | 2 | 3. Возврата назад нет. ТЗ 2. */
  step: 1,

  /** Форма ячейки. В альфе активна только прямоугольная. ТЗ 1.1. */
  shape: 'rect',

  /** Сырые строки полей ввода. */
  fields: { ...initialFields },

  /** Состояние генерации: 'idle' | 'pending' | 'ready' | 'error'. */
  generation: 'idle',

  /** Код технической ошибки генерации: ERR-08 | ERR-09 | ERR-10 | null. */
  generationError: null,

  /** Последняя успешно построенная модель или null. */
  model: null,

  /** Снимок параметров последней успешной модели. ТЗ 9.2. */
  modelSnapshot: null,
}

/** Свежая копия начального состояния — для reset. ТЗ 15.1. */
export function makeInitialState() {
  return { ...initialState, fields: { ...initialFields } }
}
