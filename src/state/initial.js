// Начальные значения и форма дерева состояния. ТЗ v5, раздел 3.

/**
 * Значения полей ввода хранятся строками — ровно так, как их видит
 * пользователь, с запятой в роли разделителя. В число они превращаются
 * только в геометрии и валидации.
 */
export const initialFields = {
  width: '19,6',
  depth: '37',
  /** Диаметр баночки для круглой ячейки. ТЗ 4.2, минимум 30. */
  diameter: '30',
  /** Сколько баночек у пользователя. ТЗ 4.1: люди считают баночками, не сеткой. */
  jars: '9',
  nx: '3',
  ny: '3',
}

export const initialState = {
  /** Форма ячейки: 'rect' | 'round'. ТЗ 1.1. */
  shape: 'rect',

  /** Выбранная модель принтера или null. ТЗ 6.1. */
  printer: null,

  /** Галочка «У меня нет принтера». ТЗ 6.2. */
  noPrinter: false,

  /** Сырые строки полей ввода. */
  fields: { ...initialFields },

  /**
   * Номер запуска генерации. Растёт на каждую правку, завершившуюся
   * пересчётом, и только он запускает воркер: сравнивать параметры нельзя —
   * пока человек печатает, в поле лежит незаконченная строка. ТЗ 9.
   *
   * Начинается с 1: модель строится сразу при открытии.
   */
  runId: 1,

  /**
   * Состояние генерации: 'pending' | 'ready' | 'error'. Простоя ('idle') нет:
   * счёт идёт с открытия и после каждой завершённой правки.
   */
  generation: 'pending',

  /** Код технической ошибки генерации: ERR-08 | ERR-09 | ERR-10 | null. */
  generationError: null,

  /** Последняя успешно построенная модель или null. */
  model: null,

  /** Снимок параметров последней успешной модели. ТЗ 9.2. */
  modelSnapshot: null,
}

/** Свежая копия начального состояния — для reset. ТЗ 15.1. */
export function makeInitialState() {
  return { ...initialState, fields: { ...initialFields } }
}
