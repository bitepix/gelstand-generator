// Тексты ошибок. ТЗ v5, раздел 16.
//
// Словарь держится отдельно от компонентов: текст никогда не выводится
// внутри поля, только в Error Block. Причин может быть несколько сразу —
// пустые Nx и Ny дают ERR-03 и ERR-04 в одном блоке.

export const messages = {
  'ERR-01': 'Укажите размер.',
  'ERR-02': 'Максимальный размер — 100 мм.',
  'ERR-03': 'Укажите количество ячеек по оси X.',
  'ERR-04': 'Укажите количество ячеек по оси Y.',
  'ERR-08': 'Не удалось сгенерировать модель. Попробуйте ещё раз.',
  'ERR-09': 'Не удалось обновить модель. Попробуйте ещё раз.',
  'ERR-10': 'Не удалось завершить генерацию модели. Попробуйте ещё раз.',
}

/** Тексты для списка кодов, в том порядке, в каком коды пришли. */
export function messagesFor(codes) {
  return codes.map((code) => messages[code]).filter(Boolean)
}
