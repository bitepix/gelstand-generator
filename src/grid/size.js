// Габарит подставки по сетке. ТЗ v5, разделы 7 и 12.
//
// Форма ячейки сюда не проникает: наружу отдаются две функции одного вида
// `(nx, ny) => { x, y }`. У прямоугольной габарит линеен по обеим осям, у
// гексагональной — нет: ряды нечётных колонок сдвинуты, и к высоте
// добавляется апофема.
//
// Подбор сетки из количества баночек жил здесь же и удалён вместе с полем
// «Сколько у вас баночек»: Nx и Ny задаёт человек.

import { hexSize } from '../geometry/hexCell.js'

/** Габарит прямоугольной подставки. */
export const rectSize = (step) => (nx, ny) => ({ x: nx * step.x, y: ny * step.y })

/** Габарит гексагональной подставки. */
export const roundSize = (diameter) => (nx, ny) => hexSize(diameter, nx, ny)
